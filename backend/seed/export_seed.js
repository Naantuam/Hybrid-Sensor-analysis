// Exports the local SQLite telemetry into a sanitised, committable seed file.
// Usage: node backend/seed/export_seed.js [path/to/sensor_local.db]
// Network identifiers (IP, SSID) are replaced with placeholders; rows are marked
// synced = 1 so a re-seeded instance does not push duplicates to PostgreSQL.
const { DatabaseSync } = require('node:sqlite');
const path = require('path');
const fs = require('fs');

const dbPath = process.argv[2] || path.join(__dirname, '..', 'sensor_local.db');
const outPath = path.join(__dirname, 'demo_seed.sql');
const db = new DatabaseSync(dbPath, { readOnly: true });

const quote = v => v === null || v === undefined ? 'NULL'
    : typeof v === 'number' || typeof v === 'bigint' ? String(v)
    : `'${String(v).replace(/'/g, "''")}'`;

const sanitise = {
    sessions: row => ({ ...row, ip_address: '0.0.0.0', ssid: row.ssid ? 'demo-network' : row.ssid, synced: 1 }),
    sensor_events: row => ({ ...row, synced: 1 }),
    threat_alerts: row => ({ ...row, synced: 1 }),
};

const lines = ['-- Demo telemetry seed generated by export_seed.js. Network identifiers are sanitised.', 'BEGIN;'];
for (const table of Object.keys(sanitise)) {
    const rows = db.prepare(`SELECT * FROM ${table} ORDER BY id`).all().map(sanitise[table]);
    for (const row of rows) {
        const cols = Object.keys(row);
        lines.push(`INSERT INTO ${table} (${cols.join(', ')}) VALUES (${cols.map(c => quote(row[c])).join(', ')});`);
    }
    console.log(`[+] ${table}: ${rows.length} rows`);
}
lines.push('COMMIT;', '');
fs.writeFileSync(outPath, lines.join('\n'));
console.log(`[+] Wrote ${outPath}`);
